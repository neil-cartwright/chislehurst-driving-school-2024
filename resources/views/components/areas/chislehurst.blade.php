                                Box junctions. These have criss-cross yellow lines painted on the road (download ‘Road
                                markings’). You <span class="has-text-danger">MUST NOT</span> enter the box until your
                                exit road or lane is clear. However,
                                <strong>
                                    you may enter the box and wait when you want to turn right, and are only stopped
                                    from
                                    doing so by oncoming traffic
                                </strong>, or by other vehicles waiting to turn right. At signalled
                                roundabouts you <span class="has-text-danger">MUST NOT</span> enter the box unless you
                                can cross over it completely without
                                stopping.
                                <span class="has-text-danger">Law TSRGD regs 10(1) & 29(2)</span>
                            </p>
                        </blockquote>
