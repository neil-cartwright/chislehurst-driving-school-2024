                    <p class="has-text-weight-bold">How to deal with small roundabouts</p>
                    <p>When taking driving lessons in Mottingham village you will probably need to deal with the small
                        roundabouts near Lidl.
                    </p>
                    <p>Lots of smaller roundabouts have an 'apron', which is a slightly raised, textured
                        area surrounding the central island. <span class="has-text-weight-bold">You should not drive on
                            this area</span>
                        unless your vehicle is so long that it cannot be avoided. The purpose of these areas is
                        to
                        force regular vehicles to take a wider, slower turn while allowing larger vehicles the room to
                        manoeuvre around the island.</p>
                    <blockquote>
                        <p class="has-text-weight-bold">Highway code rule 188</p>
                        <p>Mini roundabouts</p>
                        <p>All vehicles MUST pass round the central markings except large vehicles which are physically
                            incapable of doing so.</p>
                    </blockquote>
                    <p>When turning right here, be aware of vehicles trying to pass on your left, and of pedestrians
                        using Lidl.</p>
                    <p class="has-text-weight-bold">
                        Using indicators
                    </p>
                    <ul>
                        <li><strong>Going left</strong>: indicate left on approach</li>
                        <li><strong>Going straight</strong>: do not indicate on approach. Indicate left after you pass
                            the exit before the one you
                            need</li>
                        <li><strong>Going right</strong>: indicate right as you approach. Indicate left as you leave
                        </li>
                    </ul>
                    <p>When leaving a roundabout you must indicate left. However at mini-roundabouts sometimes there is
                        not time to do this.</p>

