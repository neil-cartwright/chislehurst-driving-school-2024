                    <p>One way systems are generally easy to navigate but there are some features which can catch out
                        new drivers.</p>
                    <p> A
                        <strong>
                            common
                            mistake
                        </strong> learner drivers make, which can sometimes lead to a driving test fail, is <strong>
                            not positioning
                            to
                            the right hand lane when turning right at the end of a one-way street.
                        </strong>
                    </p>
                    <p>
                        Make sure you get plenty of practice of driving around
                        various one way systems and <a href="/signs/regulatory-signs">know the regulatory signs</a>
                    </p>
                    </p>
                    <blockquote class="mb-4">
                        <p>Highway code rule 143</p>

                        <p>One-way streets. Traffic <span class="has-text-danger">MUST</span> travel in the direction
                            indicated by signs. Buses and/or cycles
                            may have a contraflow lane. Choose the correct lane for your exit as soon as you can. Do not
                            change lanes suddenly. Unless road signs or markings indicate otherwise, you should use</p>

                        <ul>
                            <li>the left-hand lane when going left</li>
                            <li>the right-hand lane when going right</li>
                            <li>the most appropriate lane when going straight ahead. Remember – traffic could be passing
                                on both sides.</li>
                        </ul>
                    </blockquote>
