                       <p class="title is-size-6">How to deal with pedestrian crossings</p>
                       <p>Learning to drive in Lewisham will involve dealing safely with different
                           types
                           of pedestrian crossing. </p>
                       <p>There are five main types:</p>
                       <ul>
                           <li>Zebra and Parallel </li>
                           <li><abbr title="Pedestrian User Friendly">Puffin </abbr></li>
                           <li>Toucan</li>
                           <li>Equestrian </li>
                           <li>Pelican</li>
                       </ul>
                       <details class="cursor-pointer mb-4">
                           <summary class="has-text-weight-bold">Which type of traffic light crossing has a flashing
                               amber
                               phase?
                           </summary>
                           <p>The Pelican. You must give way to pedestrians on the crossing when the amber light is
                               flashing.</p>
                       </details>

                       <details class="cursor-pointer mb-4">
                           <summary class="has-text-weight-bold">Which type of crossing is also for cyclists?
                           </summary>
                           <p><span class="has-text-weight-bold">Toucan</span> crossings are for pedestrians and
                               cyclists.
                               <span class="has-text-weight-bold">Parallel</span> crossings are zebra crossings
                               with a section for cyclists.
                           </p>
                       </details>

                       <blockquote>
                           <p>Highway code rule 193</p>
                           <p>
                               You should take extra care where the view of either side of the crossing is blocked by
                               queuing
                               traffic or incorrectly parked vehicles. Pedestrians may be crossing between stationary
                               vehicles.
                           </p>
                       </blockquote>
                       <p>When approaching a pedestrian crossing check behind you in the mirrors, be prepared to slow
                           down
                           and to stop,
                           especially when your view is restricted by stationary traffic.</p>

                       <p>When dealing with zebra crossings a <strong>common mistake</strong> new drivers make is to
                           only
                           look ahead and <strong>forget to
                               look to the sides of the crossing
                           </strong>
                           when approaching. </p>
                       <p>Pedestrian User Friendly Intelligent crossings, or <strong>PUFFIN</strong>s feature
                           technology
                           which makes it safer to cross for those who are visually impaired or less mobile.</p>
